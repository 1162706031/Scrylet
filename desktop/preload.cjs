const { contextBridge, ipcRenderer } = require("electron");
contextBridge.exposeInMainWorld("snap", {
  state: () => ipcRenderer.invoke("snap:state"),
  startupMetrics: () => ipcRenderer.invoke("snap:startup-metrics"),
  startupObserved: (phase) => ipcRenderer.invoke("snap:startup-observed", phase),
  refreshCode: () => ipcRenderer.invoke("snap:refresh-code"),
  selectNetwork: (address) => ipcRenderer.invoke("snap:network", address),
  revoke: (id) => ipcRenderer.invoke("snap:revoke", id),
  pause: (value) => ipcRenderer.invoke("snap:pause", value),
  permission: () => ipcRenderer.invoke("snap:permission"),
  openMousePermission: () => ipcRenderer.invoke("snap:mouse-permission"),
  testCapture: () => ipcRenderer.invoke("snap:test-capture"),
  copyAddress: () => ipcRenderer.invoke("snap:copy"),
  openPhonePreview: () => ipcRenderer.invoke("snap:preview"),
  quit: () => ipcRenderer.invoke("snap:quit"),
  captureAndSend: () => ipcRenderer.invoke("snap:capture-send"),
  selectRegion: () => ipcRenderer.invoke("snap:capture-region"),
  cancelRegion: () => ipcRenderer.invoke("snap:capture-cancel"),
  saveCaptureSettings: (settings) => ipcRenderer.invoke("snap:capture-settings", settings),
  suspendCaptureShortcuts: (value) => ipcRenderer.invoke("snap:capture-suspend", value),
  onCaptureState: (callback) => ipcRenderer.on("snap:capture-state", (_event, state) => callback(state)),
  activityLog: () => ipcRenderer.invoke("snap:activity"),
  cacheInfo: () => ipcRenderer.invoke("snap:cache-info"),
  clearCache: () => ipcRenderer.invoke("snap:cache-clear"),
  providers: () => ipcRenderer.invoke("snap:providers"),
  saveProvider: (change) => ipcRenderer.invoke("snap:provider-save", change),
});
