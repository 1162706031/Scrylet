const { test, expect } = require("@playwright/test");
const { nodePhone } = require("./fixture.cjs");
const { open, send } = require("./helpers.cjs");
let fixture;
test.beforeAll(async () => { fixture = await nodePhone(); });
test.afterAll(async () => fixture?.stop());
test.beforeEach(async () => fixture.resetDevices());
test("Phone shows model selection and directs API configuration to the desktop", async ({ page }, info) => {
  await open(page, fixture);
  const id = await send(page, fixture, "模型配置位于电脑");
  await page.locator("#chat-input").fill("手机草稿保留");
  await expect(page.getByText("已保存", { exact: true })).toBeVisible();
  await expect(page.getByLabel("当前模型")).toBeVisible();
  await expect(page.getByText("电脑端设置模型")).toBeVisible();
  await expect(page.locator('a[href^="/snap/models"]')).toHaveCount(0);
  await page.screenshot({ path: info.outputPath("phone-model-selection.png"), fullPage: true });
  await page.reload();
  await expect(page).toHaveURL(fixture.url + "/c/" + id);
  await expect(page.locator("#chat-input")).toHaveValue("手机草稿保留");
});
